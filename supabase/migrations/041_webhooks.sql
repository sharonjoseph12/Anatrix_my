-- ============================================================================
-- 2. public.webhook_deliveries — append-only delivery log
-- ============================================================================
-- One row per dispatch attempt. The dispatcher INSERTs a 'pending' row
-- first to obtain a `delivery.id` for the X-Antarix-Delivery-Id header,
-- then UPDATEs the row to its terminal state. The retry cron
-- (`retryFailedDeliveries`) finds rows in the 'failed' state and
-- re-dispatches with attempt_number + 1.
--
-- `payload` is the exact bytes we signed; the partner can replay this
-- to verify a delivery without re-firing. `response_body_excerpt` is
-- truncated to 2KB so a partner error response can't bloat the row.

create table if not exists public.webhook_deliveries (
  id                     uuid primary key default gen_random_uuid(),
  endpoint_id            uuid not null references public.webhook_endpoints(id) on delete cascade,
  event_type             text not null,
  event_id               uuid not null,
  payload                jsonb not null,
  attempt_number         integer not null default 1,
  status                 text not null,
  response_status        integer,
  response_body_excerpt  text,
  error_message          text,
  requested_at           timestamptz not null default now(),
  responded_at           timestamptz,
  constraint webhook_deliveries_status_chk
    check (status in ('pending', 'succeeded', 'failed', 'exhausted'))
);

alter table public.webhook_deliveries
  add column if not exists endpoint_id            uuid references public.webhook_endpoints(id) on delete cascade;
alter table public.webhook_deliveries
  add column if not exists event_type             text;
alter table public.webhook_deliveries
  add column if not exists event_id               uuid;
alter table public.webhook_deliveries
  add column if not exists payload                jsonb;
alter table public.webhook_deliveries
  add column if not exists attempt_number         integer not null default 1;
alter table public.webhook_deliveries
  add column if not exists status                 text;
alter table public.webhook_deliveries
  add column if not exists response_status        integer;
alter table public.webhook_deliveries
  add column if not exists response_body_excerpt  text;
alter table public.webhook_deliveries
  add column if not exists error_message          text;
alter table public.webhook_deliveries
  add column if not exists requested_at           timestamptz not null default now();
alter table public.webhook_deliveries
  add column if not exists responded_at           timestamptz;

-- The retry cron scans by (status, attempt_number, requested_at); the
-- diagnostic queries from the future v2 web UI sort by requested_at desc.
create index if not exists webhook_deliveries_retry_idx
  on public.webhook_deliveries(status, attempt_number, requested_at)
  where status = 'failed';

create index if not exists webhook_deliveries_endpoint_idx
  on public.webhook_deliveries(endpoint_id, requested_at desc);

create index if not exists webhook_deliveries_event_id_idx
  on public.webhook_deliveries(event_id);

alter table public.webhook_deliveries enable row level security;
-- No policies. Service-role only. The retry cron is a service-role caller;
-- partners read their own deliveries via a future webhook-list-deliveries
-- Edge Function (out of scope v1; see docs/webhooks.md §Open items).


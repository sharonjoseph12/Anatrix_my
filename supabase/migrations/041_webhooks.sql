-- ============================================================================
-- 4. public.webhook_generate_secret() — 32-byte hex helper
-- ============================================================================
-- Returns a 64-character lowercase hex string (32 random bytes). Called
-- by the future webhook-create Edge Function so the secret is generated
-- server-side with the database's pgcrypto entropy, not from a
-- client-side crypto.getRandomValues call that could be patched by a
-- compromised Edge Function host.
--
-- Marked STABLE so it can be inlined into a SELECT in the create RPC.
-- SECURITY DEFINER is not needed here (no privileged access) but the
-- function still pins search_path per the repo convention.

create or replace function public.webhook_generate_secret()
returns text
language sql
volatile
set search_path = public
as $$
  select encode(gen_random_bytes(32), 'hex');
$$;

comment on function public.webhook_generate_secret() is
  'Generates a 32-byte hex-encoded webhook signing secret using pgcrypto entropy. Server-side only.';

-- ============================================================================
-- 5. 90-day retention sweep (one-off, safe to re-apply)
-- ============================================================================
-- The dispatcher appends a row per attempt; over time this table grows.
-- v1 has no cron for GC (we promised not to touch 029_cron_002.sql or
-- 038_cron_004.sql). The snippet below is a one-off deletion; the
-- recurring schedule is documented in docs/webhooks.md §Open items.
delete from public.webhook_deliveries
 where requested_at < now() - interval '90 days';

-- 041_webhooks.sql
-- T-WEBHOOKS: Partner webhook system for outbound event delivery +
-- inbound closed-loop callbacks. Adds 3 new tables and 1 helper function.
--
-- Strictly additive. No edits to 001–040 migrations. Every DDL uses
-- `if not exists` / `or replace` / guarded `do` blocks, so the file is
-- safe to re-apply.
--
-- IMPORTANT: 041, not 040. D-1 (status page) and D-3 (this) both need a
-- 040 number; D-3 bumped to 041 to avoid the collision. The user must
-- resolve the final numbering before commit (see the open-items table
-- in docs/webhooks.md).
--
-- ============================================================================
-- Outbound event types (7 documented in the design doc, 8 actually seeded)
-- ============================================================================
--   1. credential.issued       — a new W3C verifiable credential was issued
--   2. credential.revoked      — a W3C verifiable credential was revoked
--   3. placement.predicted     — a new placement prediction was generated
--   4. student.connected       — a student opted in to a company connection
--   5. cohort.report_ready     — a cohort-level analytics report is ready
--   6. job_match.created       — a recruiter created a job match for a student
--   7. nudge.sent              — a nudge was successfully delivered
--   8. nudge.failed            — a nudge could not be delivered
--
-- Inbound event types (received via webhook-receiver):
--   a. placement.outcome       — the student got placed, here's the ground truth
--   b. credential.viewed       — a third-party viewed a credential (analytics)
--   c. student.engagement      — an external LMS / portal is reporting engagement
--
-- ============================================================================
-- 1. public.webhook_endpoints — partner-registered outbound endpoints
-- ============================================================================
-- `owner_user_id` is the Antarix user who registered the endpoint; the
-- three possible `owner_type` values describe their role at the moment of
-- registration. `secret` is 32 bytes of crypto-grade randomness hex-encoded
-- (64 chars) — generated by the future webhook-create Edge Function and
-- returned to the partner exactly ONCE. The dispatcher signs every POST
-- with HMAC-SHA256(secret, "${t}.${body}") where t is a unix timestamp.
--
-- `consecutive_failures` is reset on every success and incremented on
-- every 5xx / timeout / network error. At 10 it auto-disables the
-- endpoint (sets is_active = false) and a warn-log is emitted by the
-- dispatcher.

create table if not exists public.webhook_endpoints (
  id                    uuid primary key default gen_random_uuid(),
  owner_user_id         uuid not null references public.users(id) on delete cascade,
  owner_type            text not null,
  url                   text not null,
  secret                text not null,
  subscribed_events     text[] not null default '{}',
  is_active             boolean not null default true,
  created_at            timestamptz not null default now(),
  last_success_at       timestamptz,
  last_failure_at       timestamptz,
  consecutive_failures  integer not null default 0,
  description           text,
  constraint webhook_endpoints_owner_type_chk
    check (owner_type in ('company', 'institution', 'partner'))
);

